#!/usr/bin/env python3
"""Compile the jason SSDT sources to AML with the ACPICA iASL compiler.

RSDP is generated by the EDK II ACPI implementation, not by iASL. MADT is
generated by madt_gen.c after verified GIC addresses have been configured.

Usage:
    python3 AcpiTables/gcc_tables.py [--output <directory>]
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path


ASL_SOURCES = ("ssdt_cpu.asl", "ssdt_periph.asl")


def find_iasl():
    """Find iASL in PATH or a common local installation directory."""
    candidates = [
        shutil.which("iasl"),
        "/usr/bin/iasl",
        "/opt/acpica/bin/iasl",
        str(Path.home() / ".local" / "bin" / "iasl"),
    ]
    for candidate in candidates:
        if candidate and os.path.isfile(candidate):
            return candidate
    return None


def compile_asl(iasl: str, src: Path, out_dir: Path):
    """Compile one ASL file and return its AML path, or None on failure."""
    aml = out_dir / f"{src.stem}.aml"
    result = subprocess.run(
        [iasl, "-p", str(aml.with_suffix("")), str(src)],
        capture_output=True,
        text=True,
        cwd=out_dir,
    )
    if result.stdout:
        print(result.stdout, end="")
    if result.returncode != 0 or not aml.is_file():
        print(f"[ERROR] iASL failed for {src.name}: {result.stderr}", file=sys.stderr)
        return None

    print(f"[OK] {src.name} -> {aml} ({aml.stat().st_size} bytes)")
    return aml


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", help="Output directory for AML files")
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent
    out_dir = Path(args.output).resolve() if args.output else script_dir / "build" / "acpi_blobs"
    out_dir.mkdir(parents=True, exist_ok=True)

    iasl = find_iasl()
    if iasl is None:
        print("[ERROR] iASL not found; install the ACPICA tools.", file=sys.stderr)
        return 1

    failures = 0
    for name in ASL_SOURCES:
        src = script_dir / name
        if not src.is_file() or compile_asl(iasl, src, out_dir) is None:
            failures += 1

    if failures:
        print(f"[ERROR] {failures} ACPI source(s) failed to compile.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
